_ORDER = sorted(CATS.items(), key=lambda kv: -max(len(k) for k in kv[1]["keys"]))


def cat_of(text, props=None):
    """从标题/型号/参数文本认品类 → (key, profile)；认不出 (None, None)。"""
    blob = str(text or "")
    if props:
        try:
            blob += " " + " ".join("%s%s" % (k, v) for k, v in props)
        except Exception:
            pass
    for key, p in _ORDER:
        for k in p["keys"]:
            if k and k in blob:
                return key, p
    return None, None


def dims_text(text, props=None):
    """聚光 PROMPT 用：必讲维度 + 禁写，认不出品类给通用兜底。"""
    key, p = cat_of(text, props)
    if not p:
        return ("品类：未识别（按参数表里真实存在的项逐条写，有容量写容量、有功率写功率、"
                "有能效写能效，没有的项一律不写）")
    return ("品类：%s\n必讲维度（有数据才写，没有就跳过，顺序照这个来）：%s\n"
            "禁写（这些说法一律不许出现）：%s"
            % (p["name"], "、".join(p["dims"]), "、".join(p["ban"])))


